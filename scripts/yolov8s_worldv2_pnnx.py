    def _block_diag1x1(self, w):
        # w: [1, M, J, N]（M=注意力维数=类别数, J=头数, N=特征维数）
        # -> 块对角 1x1 卷积权重 [J*M, J*N, 1, 1]
        # 对应 einsum('ijnkl,imjn->ijklm')：输出 (j,m) 仅由同 head j 的 (j,n) 贡献
        M, J, N = w.shape[1], w.shape[2], w.shape[3]
        B = torch.zeros(J * M, J * N)
        for j in range(J):
            B[j * M:(j + 1) * M, j * N:(j + 1) * N] = w[0, :, j, :]
        return B.reshape(J * M, J * N, 1, 1)

